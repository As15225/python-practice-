# Examples of common Python escape characters
print('Single quote inside a string: \'Hello\'')
print("Backslash example: C:\\Users\\Name")
print("New line example:\nLine 1\nLine 2")
print("Tab example:\tColumn1\tColumn2")
print("Backspace example: ABC\bD")

# You can also combine them:
print("Quote, newline, and tab: \"Hello\"\n\tWelcome")

